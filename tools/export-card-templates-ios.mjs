/*
 * Generates the native card-template manifest from the same data the web picker uses.
 * Keeping one manifest prevents template names, categories, focal points and readability
 * defaults from drifting between platforms.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(resolve(root, "lib/cardTemplates.generated.ts"), "utf8");
const json = source
  .replace(/^.*?=\s*/s, "")
  .replace(/\s+as const;?\s*$/, "");
const templates = JSON.parse(json);

const categoryCases = {
  banks: "banks",
  "credit-cards": "creditCards",
  "digital-banks": "digitalBanks",
  "e-wallets": "eWallets",
  membership: "membership",
  prepaid: "prepaid",
};

const quote = (value) => JSON.stringify(value);
const rows = templates.map((template) => {
  const path = template.src.replace(/^\/card-templates\//, "");
  const category = categoryCases[template.category];
  if (!category) throw new Error(`Unknown template category: ${template.category}`);
  return `        CardTemplate(
            id: ${quote(template.id)},
            name: ${quote(template.name)},
            category: .${category},
            resourcePath: ${quote(path)},
            focalX: ${template.focal[0]}, focalY: ${template.focal[1]},
            sample: RGBSample(red: ${template.sample[0]}, green: ${template.sample[1]}, blue: ${template.sample[2]}),
            fallbackHex: ${quote(template.fallback)},
            scrim: .${template.scrim}, textMode: .${template.textMode}, chip: ${template.chip}
        )`;
});

const output = `// Generated by tools/export-card-templates-ios.mjs — do not edit by hand.
// Source: lib/cardTemplates.generated.ts

import Foundation

enum CardTemplates {
    static let all: [CardTemplate] = [
${rows.join(",\n")}
    ]

    static let byID: [String: CardTemplate] = Dictionary(uniqueKeysWithValues: all.map { ($0.id, $0) })
}
`;

const destination = resolve(root, "ios/Pesolita/Pesolita/Generated/CardTemplates.swift");
mkdirSync(dirname(destination), { recursive: true });
writeFileSync(destination, output);
console.log(`Wrote ${templates.length} card templates to ${destination}`);
